"""
Rank per-image detection quality (best/worst by FP+FN) from cached
predictions -- no inference, no retraining. Surfaces the worst offenders
for manual annotation-quality review.

Overlay paths point at the existing
'<run_dir>/overlays/<split>/visualizations/<stem>_matched.png' images
already generated by run_experiments.py, so a human can open them directly.
"""

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent / "training"))
from train_yolo import load_predictions_yolo_format, match_objects_hungarian

sys.path.insert(0, str(Path(__file__).parent))
from multilayer_containment import load_image_annotations

ROOT = Path(__file__).parent.parent.parent / "CryoAI"

GT_EXCLUDE = {"non-EV", "items-nfaR"}
MATCH_IOU = 0.5


def score_split(coco_path: Path, img_dir: Path, pred_dir: Path, split_label: str):
    rows = []
    for img, entries_all in load_image_annotations(coco_path):
        entries = [(aid, cat, m) for aid, cat, m in entries_all if cat not in GT_EXCLUDE]
        img_path = img_dir / img["file_name"]
        pred_path = pred_dir / f"{img_path.stem}.txt"
        if not img_path.exists() or not pred_path.exists():
            continue
        w, h = img["width"], img["height"]
        pred_masks, confidences, pred_classes = load_predictions_yolo_format(str(pred_path), w, h)
        gt_masks = [m for _, _, m in entries]

        matches, unmatched_preds, unmatched_gts = match_objects_hungarian(pred_masks, gt_masks, iou_threshold=MATCH_IOU)
        tp, fp, fn = len(matches), len(unmatched_preds), len(unmatched_gts)
        n_gt = len(gt_masks)
        precision = tp / (tp + fp) if (tp + fp) else 1.0
        recall = tp / (tp + fn) if (tp + fn) else 1.0
        f1 = 2 * precision * recall / (precision + recall) if (precision + recall) else 0.0

        rows.append({
            "split": split_label, "image": img["file_name"], "n_gt": n_gt,
            "tp": tp, "fp": fp, "fn": fn, "f1": f1,
            "overlay": pred_dir.parent.parent / "overlays" / split_label / "visualizations" / f"{img_path.stem}_matched.png",
        })
    return rows


def print_rankings(label: str, rows: list, top_n: int):
    rows_nonempty = [r for r in rows if r["n_gt"] > 0]
    print("=" * 100)
    print(f"{label} -- {len(rows)} images scored")
    print("=" * 100)

    print(f"\nTOP {top_n} BEST (fewest errors, weighted toward busier images):")
    best = sorted(rows_nonempty, key=lambda r: (r["fp"] + r["fn"], -r["n_gt"]))[:top_n]
    for r in best:
        print(f"  [{r['split']:>5}] {r['image']:<55} n_gt={r['n_gt']:>3} TP={r['tp']:>3} FP={r['fp']:>2} FN={r['fn']:>2} F1={r['f1']:.3f}")
        print(f"          overlay: {r['overlay']}  exists={r['overlay'].exists()}")

    print(f"\nTOP {top_n} WORST (most errors):")
    worst = sorted(rows_nonempty, key=lambda r: -(r["fp"] + r["fn"]))[:top_n]
    for r in worst:
        print(f"  [{r['split']:>5}] {r['image']:<55} n_gt={r['n_gt']:>3} TP={r['tp']:>3} FP={r['fp']:>2} FN={r['fn']:>2} F1={r['f1']:.3f}")
        print(f"          overlay: {r['overlay']}  exists={r['overlay'].exists()}")
    print()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dataset", default="roboflow_20260713_all_layer_singleclass",
                         help="Folder name under 'training outputs/'")
    parser.add_argument("--source-name", default="roboflow - 20260713 all layer label",
                         help="Folder name under 'training images/' holding the raw Roboflow COCO export")
    parser.add_argument("--model-run-dir", default="2026-07-13_181034_y8_1440_24b_300ep_Run_14",
                         help="Run folder name under '<dataset>/runs/' whose cached predictions to rank")
    parser.add_argument("--split", choices=["train", "valid", "test", "all"], default="all",
                         help="Which COCO split to score; 'all' reports each split plus combined")
    parser.add_argument("--top-n", type=int, default=15)
    args = parser.parse_args()

    source_root = ROOT / "training images" / args.source_name
    dataset_root = ROOT / "training outputs" / args.dataset
    run_dir = dataset_root / "runs" / args.model_run_dir

    split_map = {"train": "train", "valid": "val"}
    if (source_root / "test" / "_annotations.coco.json").exists():
        split_map["test"] = "test"

    splits_to_run = list(split_map) if args.split == "all" else [args.split]

    all_rows = []
    for coco_split in splits_to_run:
        yolo_split = split_map[coco_split]
        coco_path = source_root / coco_split / "_annotations.coco.json"
        img_dir = dataset_root / "images" / yolo_split
        pred_dir = run_dir / "predictions" / yolo_split
        rows = score_split(coco_path, img_dir, pred_dir, yolo_split)
        all_rows.extend(rows)
        print_rankings(yolo_split.upper(), rows, args.top_n)

    if len(splits_to_run) > 1:
        print_rankings("COMBINED", all_rows, args.top_n)


if __name__ == "__main__":
    main()
